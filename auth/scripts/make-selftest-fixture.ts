// Writes src/selftest-fixture.ts: one registration and one sign-in of the fixture passkey, made by the
// software authenticator, for the Worker's GET /selftest route (a route that exercises the library
// with no client, so that `curl` alone can show the library working in the built Worker).
//
//   node scripts/make-selftest-fixture.ts
//
// The registration is deterministic ("none" attestation has no signature). The sign-in holds one
// ECDSA signature, which is random: that is why the file is generated once and kept. Any signature
// by the fixture key over the same data is as good; the Worker verifies it for real on every call.

import { writeFileSync } from 'node:fs'
import { generateAuthenticationOptions, generateRegistrationOptions } from '@simplewebauthn/server'
import {
  CHALLENGE_BYTES,
  CREDENTIAL_ID,
  ES256_PRIVATE_JWK,
  ORIGIN,
  OTHER_CHALLENGE_BYTES,
  RP_ID,
  RP_NAME,
  USER_ID,
  USER_NAME,
} from '../test/support/fixtures.ts'
import { SoftwareAuthenticator } from '../test/support/software-authenticator.ts'

const authenticator = await SoftwareAuthenticator.create({
  credentialId: CREDENTIAL_ID,
  privateJwk: ES256_PRIVATE_JWK,
})
const registrationOptions = await generateRegistrationOptions({
  rpName: RP_NAME,
  rpID: RP_ID,
  userName: USER_NAME,
  userID: USER_ID,
  challenge: CHALLENGE_BYTES,
})
const fullRegistration = await authenticator.createCredential(registrationOptions, {
  origin: ORIGIN,
})
// Only what the library reads: the Worker carries this file in its bundle.
const registration = {
  id: fullRegistration.id,
  rawId: fullRegistration.rawId,
  type: fullRegistration.type,
  clientExtensionResults: fullRegistration.clientExtensionResults,
  response: {
    clientDataJSON: fullRegistration.response.clientDataJSON,
    attestationObject: fullRegistration.response.attestationObject,
    transports: fullRegistration.response.transports,
  },
}
const authenticationOptions = await generateAuthenticationOptions({
  rpID: RP_ID,
  challenge: OTHER_CHALLENGE_BYTES,
})
const fullAssertion = await authenticator.getAssertion(authenticationOptions, { origin: ORIGIN })
const assertion = {
  id: fullAssertion.id,
  rawId: fullAssertion.rawId,
  type: fullAssertion.type,
  clientExtensionResults: fullAssertion.clientExtensionResults,
  response: fullAssertion.response,
}

const source = `// GENERATED by scripts/make-selftest-fixture.ts, kept in the repository: see that file.
// A registration and a sign-in of the fixture passkey (fixed ES256 key, credential id 0x01..0x10,
// RP cms.example.test), for GET /selftest.
import type { AuthenticationResponseJSON, RegistrationResponseJSON } from '@simplewebauthn/server'

/** The challenge of the registration and the one of the sign-in, as the library hands them out. */
export const SELFTEST_CHALLENGES = {
  registration: ${JSON.stringify(registrationOptions.challenge)},
  authentication: ${JSON.stringify(authenticationOptions.challenge)},
}

export const SELFTEST_REGISTRATION: RegistrationResponseJSON = ${JSON.stringify(registration, null, 2)}

export const SELFTEST_ASSERTION: AuthenticationResponseJSON = ${JSON.stringify(assertion, null, 2)}
`
writeFileSync(new URL('../src/selftest-fixture.ts', import.meta.url), source)
console.log('wrote src/selftest-fixture.ts')
