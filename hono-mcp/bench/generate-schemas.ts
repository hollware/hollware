// Generates src/mcp/schemas.generated.ts: the JSON Schemas the Zod server advertises, captured from
// its own tools/list answer so they are exactly what clients see today. Run in Node 24:
//   node bench/generate-schemas.ts
import { createMcpHandler } from '@modelcontextprotocol/server'
import { writeFileSync } from 'node:fs'
import { resolve } from 'node:path'
import { buildServer } from '../src/mcp/server.ts'

type ListedTool = { name: string; inputSchema: unknown; outputSchema: unknown }

const handler = createMcpHandler(buildServer, { legacy: 'reject' })
const response = await handler.fetch(
  new Request('http://localhost/mcp', {
    method: 'POST',
    headers: {
      'content-type': 'application/json',
      accept: 'application/json, text/event-stream',
      'mcp-protocol-version': '2026-07-28',
      'mcp-method': 'tools/list',
    },
    body: JSON.stringify({
      jsonrpc: '2.0',
      id: 1,
      method: 'tools/list',
      params: {
        _meta: {
          'io.modelcontextprotocol/protocolVersion': '2026-07-28',
          'io.modelcontextprotocol/clientInfo': { name: 'generator', version: '0.0.0' },
          'io.modelcontextprotocol/clientCapabilities': {},
        },
      },
    }),
  }),
)
const { result } = (await response.json()) as { result: { tools: ListedTool[] } }

const schemas = Object.fromEntries(
  result.tools.map((tool) => [tool.name, { input: tool.inputSchema, output: tool.outputSchema }]),
)

const header = `// Generated by bench/generate-schemas.ts from src/mcp/schemas.ts. Do not edit by hand:
// test/node/precomputed.node.test.ts fails when this file differs from what the Zod server advertises.
import type { JsonSchemaType } from '@modelcontextprotocol/server'

type ToolSchemas = { input: JsonSchemaType; output: JsonSchemaType }
`
const names = Object.keys(schemas)
const shape = names.map((name) => `  ${name}: ToolSchemas`).join('\n')
writeFileSync(
  resolve(import.meta.dirname, '../src/mcp/schemas.generated.ts'),
  `${header}\nexport const PRECOMPUTED_SCHEMAS: {\n${shape}\n} = ${JSON.stringify(schemas, null, 2)}\n`,
)
console.log(`wrote ${names.length} tools: ${names.join(', ')}`)
